#!/usr/bin/env node
/**
 * Dependency-free client packaging, not a general JavaScript bundler.
 *
 * src/client contains ordinary CommonJS modules with explicit local imports.
 * This manifest is the client boundary: no directory walking, inferred chunks,
 * host sources, or npm dependency copies. Module factories and their cache live
 * INSIDE DSH's lazy factory, so evaluating the artifact only registers one entry;
 * React and UI primitives still resolve through the platform's require function.
 */
import { readFile, mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { Script } from 'node:vm'
import { posix } from 'node:path'

const root = new URL('../', import.meta.url)
export const clientModules = Object.freeze([
  'runtime', 'constants', 'context', 'styles', 'prompts', 'settings', 'icons',
  'command-palette/copy', 'session', 'command-palette/commands', 'command-palette/repository-link', 'command-palette/index', 'settings-ui', 'git-action',
  'plan-model', 'plan-views', 'plan-sidebar', 'plan-cards', 'index',
])
const externalModules = new Set(['react', '@deepseek-ai/dsh-client-ui-primitives'])

/** Render and validate the exact artifact without writing it (also used by tests). */
export async function renderClient() {
  const modules = await Promise.all(clientModules.map(async (name) => {
    const source = await readFile(new URL(`src/client/${name}.cjs`, root), 'utf8')
    new Script(`(function(require, module, exports) {\n${source}\n})`, { filename: `src/client/${name}.cjs` })
    const dependencies = []
    // Resolve local imports against their module, then use canonical table IDs.
    const bundledSource = source.replace(/\brequire\(['"]([^'"]+)['"]\)/g, (expression, dependency) => {
      if (externalModules.has(dependency)) return expression
      const resolved = posix.normalize(posix.join(posix.dirname(name), dependency))
      if (!(dependency.startsWith('./') || dependency.startsWith('../'))
        || !resolved.endsWith('.cjs') || !clientModules.includes(resolved.slice(0, -4))) {
        throw new Error(`${name}.cjs: undeclared client dependency ${dependency}`)
      }
      dependencies.push(`./${resolved}`)
      return `require(${JSON.stringify(`./${resolved}`)})`
    })
    return { name, source: bundledSource, dependencies }
  }))
  // Acyclic feature composition avoids partial exports and order-dependent startup.
  const visited = new Set(), active = new Set()
  function visit(name) {
    if (active.has(name)) throw new Error(`Client dependency cycle at ${name}.cjs`)
    if (visited.has(name)) return
    active.add(name)
    for (const dependency of modules.find((module) => module.name === name).dependencies) {
      if (dependency.startsWith('./')) visit(dependency.slice(2, -4))
    }
    active.delete(name)
    visited.add(name)
  }
  for (const name of clientModules) visit(name)
  const table = modules.map(({ name, source }) => {
    const indented = source.trimEnd().split('\n').map((line) => `        ${line}`).join('\n')
    return `      ${JSON.stringify(`./${name}.cjs`)}: function (require, module, exports) {\n${indented}\n      }`
  }).join(',\n')
  const output = `/** Generated by node scripts/build-client.mjs. Edit src/client/*.cjs instead. */
window.__ModuleLoader__.load({
  id: 'dsh-git-commit-agent',
  factory: (require) => {
    const modules = {
${table}
    }
    const cache = Object.create(null)
    function clientRequire(id) {
      if (!Object.prototype.hasOwnProperty.call(modules, id)) return require(id)
      if (Object.prototype.hasOwnProperty.call(cache, id)) return cache[id].exports
      const module = { exports: {} }
      cache[id] = module
      try {
        modules[id](clientRequire, module, module.exports)
      } catch (error) {
        delete cache[id]
        throw error
      }
      return module.exports
    }
    return clientRequire('./index.cjs')
  },
})
`
  new Script(output, { filename: 'dist/client/index.js' })
  return output
}

export async function buildClient() {
  const output = await renderClient()
  await mkdir(new URL('dist/client/', root), { recursive: true })
  await writeFile(new URL('dist/client/index.js', root), output)
  return output
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  if (process.argv.length > 2) throw new Error('Usage: node scripts/build-client.mjs (instrument dist/client separately for development)')
  await buildClient()
  console.log(`Built ${fileURLToPath(new URL('dist/client/index.js', root))}`)
}
